/**
  * @brief  Period elapsed callback in non blocking mode
  * @note   This function is called  when TIM1 interrupt took place, inside
  * HAL_TIM_IRQHandler(). It makes a direct call to HAL_IncTick() to increment
  * a global variable "uwTick" used as application time base.
  * @param  htim : TIM handle
  * @retval None
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  /* USER CODE BEGIN Callback 0 */

  /* USER CODE END Callback 0 */
  if (htim->Instance == TIM1)
  {
    HAL_IncTick();
  }
  /* USER CODE BEGIN Callback 1 */
	if (htim->Instance == TIM4)
	{
    static uint16_t count;
    count++;
    if(count>=40)
    {
    MyTIM_Scan();
    count=0;
	
		int16_t speed_raw = Get_Speed();
		static int16_t filter_buf[5];
		static uint8_t idx=0;
		filter_buf[idx++] = speed_raw;
		if(idx>=5) idx=0;
		int32_t sum=0; 
		for(int i=0;i<5;i++) sum += filter_buf[i];
			
		actual = sum /5;
 
	  location+=actual;

	  last_error=cur_error;
		cur_error=target-actual;
		
    if (ki != 0)				
		{
			error_Int +=cur_error;		//进行误差积分
		}
		else						
		{
			error_Int = 0;			//误差积分直接归0
		}

		out=kp*cur_error+ki*error_Int+kd*(cur_error-last_error);
		
		if(out>100)		out=100;
		if(out<-100)	out=-100;
		
		PWM_Set((int16_t)out);
    }
	}
  /* USER CODE END Callback 1 */
}

